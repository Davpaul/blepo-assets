"""Write firmware/test/test_vectors.h from the Python reference model, so the
C++ port can be checked against it:

    python3 tools/gen_test_vectors.py
    g++ -std=c++17 -O2 -I firmware firmware/test/host_test.cpp -o /tmp/belt_host_test && /tmp/belt_host_test
"""
import os, random
import beltkin as K

random.seed(7)
tables = [K.Table.rectangle(2440, 1220), K.Table.from_measurements(1260.0, 668.5, 1263.2, 671.0, 1424.0)]
out = ["// generated by tools/gen_test_vectors.py - do not edit", "struct TestTable { float p[4][2], f[4][2], pinch[4]; };",
       "struct TestVec { int table; float dz, x, y, len[4]; };", "static const TestTable test_tables[] = {"]
for t in tables:
    out.append("  {{" + ",".join(f"{{{p[0]:.6f}f,{p[1]:.6f}f}}" for p in t.P) + "},{" + ",".join(f"{{{p[0]:.6f}f,{p[1]:.6f}f}}" for p in t.F)
               + "},{" + ",".join(f"{a:.8f}f" for a in t.pinch) + "}},")
out.append("};\nstatic const TestVec test_vecs[] = {")
for ti, t in enumerate(tables):
    xs = [c[0] for c in t.C]; ys = [c[1] for c in t.C]
    for _ in range(200):
        x = random.uniform(min(xs) + 60, max(xs) - 60); y = random.uniform(min(ys) + 60, max(ys) - 60)
        dz = random.choice([0.0, 0.0, 12.0, 18.0])
        L = K.lengths(t, (x, y), dz)
        out.append(f"  {{{ti},{dz:.1f}f,{x:.4f}f,{y:.4f}f,{{" + ",".join(f"{v:.5f}f" for v in L) + "}},")
out.append("};")
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "firmware", "test", "test_vectors.h")
open(path, "w").write("\n".join(out) + "\n")
print("wrote", os.path.normpath(path), len(out) - 6, "vectors")
